//! Password complexity, history and lockout - the PAM half of what
//! `net accounts` and `secedit` do on Windows.
//!
//! Linux splits this across three mechanisms, and a run that touches only one
//! of them satisfies none of the scored checks:
//!
//! | Wanted | Where it lives |
//! |---|---|
//! | Length and character classes | `pam_pwquality` (installed if absent) |
//! | History (no reuse) | `pam_pwhistory`, via a `pam-auth-update` profile |
//! | Lockout after failed attempts | `pam_faillock` |
//! | Ageing (max/min/warn) | `login.defs`, applied by Security Hardening |
//!
//! The complexity settings are written to `/etc/security/pwquality.conf`
//! rather than as arguments on the `pam_pwquality` line in
//! `common-password`. Both work, but the PAM file is regenerated by
//! `pam-auth-update` whenever a package touches authentication, which silently
//! reverts arguments added there. `pwquality.conf` survives it.
//!
//! `pam_faillock` and `pam_pwhistory` need lines in `common-auth` and
//! `common-password`, whose order decides whether they work or lock everyone
//! out. They are added as `pam-auth-update` profiles, which compute that order,
//! and the result is checked and rolled back if unsafe - see [`crate::pam_ops`].

use pinnacle_core::models::{SystemInfo, TaskResult};
use pinnacle_core::task::Task;
use pinnacle_core::{impl_task_meta, remediation, ui};

use crate::apt;
use crate::file_ops::{self, Style};
use crate::knowledge::LOGIN_DEFS;
use crate::pam_ops::{self, COMMON_AUTH, COMMON_PASSWORD};
use async_trait::async_trait;

/// Complexity, read by `pam_pwquality` on every password change.
const PWQUALITY_CONF: &str = "/etc/security/pwquality.conf";

/// The minimum length, as the number the scored checks compare against.
const MIN_LEN: u32 = 14;

/// The package that provides `pam_pwquality`, and with it a `pam-auth-update`
/// profile that puts the module into `common-password`.
const PWQUALITY_PACKAGE: &str = "libpam-pwquality";

/// One complexity setting: the key, the value, and what it buys.
const PWQUALITY: &[(&str, &str, &str)] = &[
    ("minlen", "14", "minimum password length"),
    ("dcredit", "-1", "at least one digit"),
    ("ucredit", "-1", "at least one upper-case letter"),
    ("lcredit", "-1", "at least one lower-case letter"),
    ("ocredit", "-1", "at least one symbol"),
    (
        "difok",
        "4",
        "at least four characters must differ from the old password",
    ),
    (
        "retry",
        "3",
        "attempts allowed before the change is refused",
    ),
    (
        "maxrepeat",
        "3",
        "no more than three identical consecutive characters",
    ),
    (
        "usercheck",
        "1",
        "the password may not contain the account name",
    ),
    (
        "enforcing",
        "1",
        "the rules are enforced rather than merely warned about",
    ),
];

const PASS_MIN_LEN_WHY: &str = "obsolete under PAM, but checkers read it; matches pwquality minlen";

/// How many previous passwords are refused. Written into
/// [`pam_ops::PWHISTORY_PROFILE`]; a test keeps the two in step.
const REMEMBER: u32 = 5;

/// Failed attempts before `pam_faillock` locks the account, and for how long.
const DENY: u32 = 5;
const UNLOCK_SECONDS: u32 = 900;

pub struct PasswordPolicyTask {
    name: String,
    description: String,
    dry_run: bool,
}

impl PasswordPolicyTask {
    pub fn new() -> Self {
        Self {
            name: "Password Policy".to_string(),
            description: "Complexity, history and lockout, via PAM".to_string(),
            dry_run: false,
        }
    }
}

impl Default for PasswordPolicyTask {
    fn default() -> Self {
        Self::new()
    }
}

/// Is `pam_faillock` configured in the given `common-auth` content?
///
/// Looked for by module name rather than by exact line, because the surrounding
/// arguments differ between distributions and a string comparison would report
/// a correctly configured file as non-compliant and rewrite it every run.
pub fn faillock_configured(common_auth: &str) -> bool {
    common_auth
        .lines()
        .filter(|l| file_ops::is_active(l))
        .any(|l| l.contains("pam_faillock.so"))
}

/// Is the minimum length actually enforced? `pwquality.conf` is only read by
/// `pam_pwquality`, so a `minlen` there with the module absent from the stack
/// is a setting that does nothing - the failure that scored no points.
pub fn minlen_is_effective(common_password: &str, conf_minlen: Option<&str>) -> bool {
    pam_ops::pwquality_in_stack(common_password)
        && conf_minlen
            .and_then(|v| v.trim().parse::<u32>().ok())
            .is_some_and(|n| n >= MIN_LEN)
}

/// Make sure `pam_pwquality` is in the password stack, installing it if needed.
///
/// Debian does not ship `libpam-pwquality` by default, and without it every
/// pwquality setting - and `pam_pwhistory`, which needs its password - is inert.
/// Installing the package runs `pam-auth-update`, which adds the module itself.
async fn ensure_pwquality() -> Result<(), String> {
    let password = tokio::fs::read_to_string(COMMON_PASSWORD)
        .await
        .unwrap_or_default();
    if pam_ops::pwquality_in_stack(&password) {
        return Ok(());
    }
    if !apt::is_installed(PWQUALITY_PACKAGE).await {
        let why = "pam_pwquality enforces the minimum length and complexity";
        if apt::install(PWQUALITY_PACKAGE, why).await.is_err() {
            // A fresh image often has empty package lists.
            apt::update_lists().await;
            apt::install(PWQUALITY_PACKAGE, why).await?;
        }
    }
    let password = tokio::fs::read_to_string(COMMON_PASSWORD)
        .await
        .unwrap_or_default();
    if pam_ops::pwquality_in_stack(&password) {
        return Ok(());
    }
    // Installed but taken out of the stack (or the postinst could not run).
    pam_ops::enable_pwquality().await
}

/// Report every `/etc/pam.d` file with an `auth` line that skips the password
/// check. Read-only: which file a line belongs in, and whether the round put it
/// there on purpose, is a decision for a person, and removing the wrong `auth`
/// line can lock everyone out.
async fn report_permissive_pam() -> usize {
    let mut flagged = 0;
    let Ok(mut entries) = tokio::fs::read_dir("/etc/pam.d").await else {
        return 0;
    };
    let mut paths = Vec::new();
    while let Ok(Some(entry)) = entries.next_entry().await {
        paths.push(entry.path());
    }
    paths.sort();
    for path in paths {
        let Ok(text) = tokio::fs::read_to_string(&path).await else {
            continue;
        };
        let lines = pam_ops::permissive_auth_lines(&text);
        if lines.is_empty() {
            continue;
        }
        flagged += 1;
        let shown = path.display().to_string();
        ui::markup_line(&format!(
            "[red]✗ {} lets a login through without a password: {}[/]",
            ui::escape(&shown),
            ui::escape(&lines.join(" | "))
        ));
        remediation::record_finding(
            &shown,
            "every login checks a password",
            false,
            &format!(
                "{} - remove it by hand after checking the README does not require it",
                lines.join(" | ")
            ),
        );
    }
    if flagged == 0 {
        remediation::record_finding(
            "/etc/pam.d",
            "every login checks a password",
            true,
            "no auth line passes a login through ahead of the password check",
        );
    }
    flagged
}

#[async_trait]
impl Task for PasswordPolicyTask {
    impl_task_meta!();

    async fn read_system_state(&mut self) -> SystemInfo {
        let mut lines = Vec::new();
        for (key, _value, _why) in PWQUALITY {
            let state = file_ops::read(PWQUALITY_CONF, Style::Equals, key)
                .await
                .unwrap_or_else(|| "unreadable".to_string());
            lines.push(format!("{key} = {state}"));
        }
        let auth = tokio::fs::read_to_string(COMMON_AUTH)
            .await
            .unwrap_or_default();
        lines.push(format!("pam_faillock: {}", faillock_configured(&auth)));
        SystemInfo {
            raw_output: Some(lines.join("\n")),
            ..Default::default()
        }
    }

    async fn execute(&mut self) -> TaskResult {
        let mut result = TaskResult {
            task_name: self.name.clone(),
            success: true,
            items_attempted: PWQUALITY.len() as i32 + 5,
            ..Default::default()
        };

        // Findings only, so they run in a dry run too.
        let backdoors = report_permissive_pam().await;

        if self.dry_run {
            for (key, value, why) in PWQUALITY {
                let _ = file_ops::set(PWQUALITY_CONF, Style::Equals, key, value, why).await;
            }
            let _ = file_ops::set(
                LOGIN_DEFS,
                Style::Space,
                "PASS_MIN_LEN",
                &MIN_LEN.to_string(),
                PASS_MIN_LEN_WHY,
            )
            .await;
            ui::markup_line(&format!(
                "[cyan]Would install {PWQUALITY_PACKAGE} if pam_pwquality is not in the password \
                 stack[/]"
            ));
            ui::markup_line(&format!(
                "[cyan]Would enable pam_faillock (deny={DENY}, unlock_time={UNLOCK_SECONDS}) \
                 and pam_pwhistory (remember={REMEMBER}) through pam-auth-update, \
                 where they are not already in effect[/]"
            ));
            // Read-only in a dry run: the ledger shows what would change.
            let _ = pam_ops::remove_nullok().await;
            let _ = pam_ops::ensure_password_args(MIN_LEN, REMEMBER).await;
            ui::markup_line(&format!(
                "[cyan]Would remove nullok from the pam_unix lines and put minlen={MIN_LEN} and \
                 remember={REMEMBER} on the common-password lines, after the last \
                 pam-auth-update[/]"
            ));
            result.message = "DRY RUN: no password policy was changed.".to_string();
            return result;
        }

        let mut failures: Vec<String> = Vec::new();

        // First, so the settings below take effect and pam_pwhistory has the
        // password pam_pwquality collects.
        match ensure_pwquality().await {
            Ok(()) => result.items_succeeded += 1,
            Err(e) => {
                ui::markup_line(&format!(
                    "[yellow]⚠ pam_pwquality is not in the password stack: {}[/]",
                    ui::escape(&e)
                ));
                failures.push(format!("pam_pwquality: {e}"));
            }
        }

        for (key, value, why) in PWQUALITY {
            match file_ops::set(PWQUALITY_CONF, Style::Equals, key, value, why).await {
                Ok(()) => result.items_succeeded += 1,
                Err(e) => failures.push(format!("{key}: {e}")),
            }
        }

        // shadow-utils treats PASS_MIN_LEN as obsolete under PAM and ignores it,
        // but scoring checks read it, so it is set to agree with pwquality.
        match file_ops::set(
            LOGIN_DEFS,
            Style::Space,
            "PASS_MIN_LEN",
            &MIN_LEN.to_string(),
            PASS_MIN_LEN_WHY,
        )
        .await
        {
            Ok(()) => result.items_succeeded += 1,
            Err(e) => failures.push(format!("PASS_MIN_LEN: {e}")),
        }

        // --- lockout ---------------------------------------------------------
        //
        // Enabled through pam-auth-update rather than a hand-inserted line: in
        // `common-auth` a misplaced faillock entry makes a correct password
        // land on the lockout check, and every login fails, root's included.
        // `pam_ops` checks the resulting order and rolls back if it is unsafe.
        let auth = tokio::fs::read_to_string(COMMON_AUTH)
            .await
            .unwrap_or_default();
        if !faillock_configured(&auth) {
            result.items_attempted += 1;
            match pam_ops::enable(
                pam_ops::FAILLOCK_PROFILES,
                COMMON_AUTH,
                COMMON_AUTH,
                "accounts lock after repeated failed logins, and a correct password still logs in",
                pam_ops::auth_order_is_safe,
            )
            .await
            {
                Ok(()) => result.items_succeeded += 1,
                Err(e) => {
                    ui::markup_line(&format!(
                        "[yellow]⚠ Lockout not enabled: {}[/]",
                        ui::escape(&e)
                    ));
                    failures.push(format!("pam_faillock: {e}"));
                }
            }
        }

        let auth = tokio::fs::read_to_string(COMMON_AUTH)
            .await
            .unwrap_or_default();
        let has_faillock = faillock_configured(&auth);
        if has_faillock {
            match file_ops::set(
                "/etc/security/faillock.conf",
                Style::Equals,
                "deny",
                &DENY.to_string(),
                "failed attempts before the account locks",
            )
            .await
            {
                Ok(()) => result.items_succeeded += 1,
                Err(e) => failures.push(format!("faillock deny: {e}")),
            }
            if let Err(e) = file_ops::set(
                "/etc/security/faillock.conf",
                Style::Equals,
                "unlock_time",
                &UNLOCK_SECONDS.to_string(),
                "seconds before a locked account unlocks itself",
            )
            .await
            {
                failures.push(format!("faillock unlock_time: {e}"));
            }
        }

        // --- history ---------------------------------------------------------
        let password = tokio::fs::read_to_string(COMMON_PASSWORD)
            .await
            .unwrap_or_default();
        let history = pam_ops::history_depth(&password);
        if history.is_some_and(|r| r >= REMEMBER) {
            remediation::record_finding(
                COMMON_PASSWORD,
                &format!("the last {REMEMBER} passwords cannot be reused"),
                true,
                &format!(
                    "remember={} is already in effect",
                    history.unwrap_or_default()
                ),
            );
        } else if !pam_ops::pwquality_in_stack(&password) {
            // pam_pwhistory's use_authtok takes the password pam_pwquality
            // collected. Without pam_pwquality there is none, and every
            // password change would fail - so this is reported, not attempted.
            ui::markup_line(
                "[yellow]⚠ Password history not enabled: pam_pwquality is not in the password \
                 stack. Install libpam-pwquality, then re-run this task.[/]",
            );
            remediation::record_finding(
                COMMON_PASSWORD,
                &format!("the last {REMEMBER} passwords cannot be reused"),
                false,
                "pam_pwquality is absent, and pam_pwhistory depends on it; not enabled",
            );
        } else {
            result.items_attempted += 1;
            match pam_ops::enable(
                &[pam_ops::PWHISTORY_PROFILE],
                COMMON_PASSWORD,
                COMMON_PASSWORD,
                &format!("the last {REMEMBER} passwords cannot be reused, and a password change still works"),
                pam_ops::password_order_is_safe,
            )
            .await
            {
                Ok(()) => result.items_succeeded += 1,
                Err(e) => {
                    ui::markup_line(&format!(
                        "[yellow]⚠ Password history not enabled: {}[/]",
                        ui::escape(&e)
                    ));
                    failures.push(format!("pam_pwhistory: {e}"));
                }
            }
        }

        // --- after the last pam-auth-update ----------------------------------
        //
        // The stock `unix` profile carries `nullok`, and pam-auth-update
        // regenerates `common-password` without the arguments below, so both
        // are applied only now that nothing above will run it again.
        match pam_ops::remove_nullok().await {
            Ok(()) => result.items_succeeded += 1,
            Err(e) => {
                ui::markup_line(&format!(
                    "[yellow]⚠ nullok not removed: {}[/]",
                    ui::escape(&e)
                ));
                failures.push(format!("nullok: {e}"));
            }
        }
        match pam_ops::ensure_password_args(MIN_LEN, REMEMBER).await {
            Ok(()) => result.items_succeeded += 1,
            Err(e) => {
                ui::markup_line(&format!(
                    "[yellow]⚠ minlen/remember not set on the PAM lines: {}[/]",
                    ui::escape(&e)
                ));
                failures.push(format!("PAM minlen/remember: {e}"));
            }
        }

        if backdoors > 0 {
            failures.push(format!(
                "{backdoors} PAM file(s) let a login through without a password; see the ledger"
            ));
        }

        result.success = failures.is_empty();
        result.message = format!(
            "{} complexity settings applied; lockout {}.",
            result.items_succeeded,
            if has_faillock {
                "in effect"
            } else {
                "not in effect"
            }
        );
        if !failures.is_empty() {
            result.error_details = Some(failures.join("; "));
        }
        result
    }

    async fn verify(&mut self) -> bool {
        // Lockout and history are proved by order, not presence: a faillock
        // line in the wrong place is worse than none.
        let auth = tokio::fs::read_to_string(COMMON_AUTH)
            .await
            .unwrap_or_default();
        let password = tokio::fs::read_to_string(COMMON_PASSWORD)
            .await
            .unwrap_or_default();
        if !pam_ops::auth_order_is_safe(&auth)
            || pam_ops::has_nullok(&auth)
            || pam_ops::has_nullok(&password)
            || !pam_ops::password_args_present(&password, MIN_LEN, REMEMBER)
            || pam_ops::history_depth(&password).is_none_or(|r| r < REMEMBER)
        {
            return false;
        }
        let minlen = file_ops::read(PWQUALITY_CONF, Style::Equals, "minlen").await;
        if !minlen_is_effective(&password, minlen.as_deref()) {
            return false;
        }
        for (key, value, _why) in PWQUALITY {
            if file_ops::read(PWQUALITY_CONF, Style::Equals, key)
                .await
                .as_deref()
                != Some(*value)
            {
                return false;
            }
        }
        true
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Real `common-auth` content from Ubuntu 22.04, with and without faillock.
    const WITHOUT: &str = "\
auth    [success=1 default=ignore]      pam_unix.so nullok
auth    requisite                       pam_deny.so
auth    required                        pam_permit.so
";
    const WITH: &str = "\
auth    required                        pam_faillock.so preauth
auth    [success=1 default=ignore]      pam_unix.so nullok
auth    [default=die]                   pam_faillock.so authfail
auth    requisite                       pam_deny.so
";

    #[test]
    fn faillock_is_detected_by_module_name() {
        assert!(!faillock_configured(WITHOUT));
        assert!(faillock_configured(WITH));
    }

    /// A commented-out faillock line does nothing, and treating it as present
    /// would report lockout as configured on a machine with none.
    #[test]
    fn a_commented_faillock_line_does_not_count() {
        assert!(!faillock_configured(
            "# auth required pam_faillock.so preauth\n"
        ));
    }

    /// The stock file has no `remember=` at all, which means any previous
    /// password may be set again immediately.
    #[test]
    fn a_missing_remember_argument_reads_as_none() {
        let text = "password [success=1 default=ignore] pam_unix.so obscure yescrypt\n";
        assert_eq!(pam_ops::history_depth(text), None);
    }

    /// The profile carries the number as text; this keeps it equal to the one
    /// the task checks against, so the task never reports its own work as short.
    #[test]
    fn the_history_profile_remembers_what_the_task_requires() {
        assert!(
            pam_ops::PWHISTORY_PROFILE
                .body
                .contains(&format!("remember={REMEMBER} ")),
            "{}",
            pam_ops::PWHISTORY_PROFILE.body
        );
    }

    #[test]
    fn complexity_settings_are_complete_and_well_formed() {
        for (key, value, why) in PWQUALITY {
            assert!(!key.is_empty() && !value.is_empty() && !why.is_empty());
            assert!(!key.contains(' '), "{key} is not a pwquality key");
        }
        // The four character-class credits are what a scored check looks at.
        for required in ["minlen", "dcredit", "ucredit", "lcredit", "ocredit"] {
            assert!(
                PWQUALITY.iter().any(|(k, _, _)| *k == required),
                "{required} is missing"
            );
        }
    }

    #[test]
    fn minlen_counts_only_with_pam_pwquality_in_the_stack() {
        let with = "password requisite pam_pwquality.so retry=3\n";
        let without = "password [success=1 default=ignore] pam_unix.so obscure yescrypt\n";
        assert!(minlen_is_effective(with, Some("14")));
        assert!(minlen_is_effective(with, Some("20")));
        assert!(!minlen_is_effective(without, Some("14")));
        assert!(!minlen_is_effective(with, Some("8")));
        assert!(!minlen_is_effective(with, None));
        assert!(!minlen_is_effective(with, Some("abc")));
    }

    /// The PAM-line arguments are pure text edits, so the task's constants can
    /// be checked against them without touching `/etc/pam.d`.
    #[test]
    fn the_pam_arguments_use_the_task_constants() {
        let stock = "password requisite pam_pwquality.so retry=3\npassword [success=1 default=ignore] pam_unix.so obscure yescrypt\n";
        let out = pam_ops::with_password_args(stock, MIN_LEN, REMEMBER);
        assert!(out.contains(&format!("pam_pwquality.so retry=3 minlen={MIN_LEN}")));
        assert!(out.contains(&format!("minlen={MIN_LEN} remember={REMEMBER}")));
        assert!(pam_ops::password_args_present(&out, MIN_LEN, REMEMBER));
    }

    #[test]
    fn the_minimum_length_matches_the_pwquality_table() {
        assert!(PWQUALITY.contains(&("minlen", "14", "minimum password length")));
        assert_eq!(MIN_LEN, 14);
    }

    #[tokio::test]
    async fn a_dry_run_writes_nothing() {
        let _dry_run = pinnacle_core::run_log::dry_run_for_test();
        let mut task = PasswordPolicyTask::new();
        task.set_dry_run(true);
        let result = pinnacle_core::ui::capture(task.execute()).await.0;
        assert!(result.success);
        assert!(result.message.starts_with("DRY RUN"), "{}", result.message);
        assert!(
            !std::path::Path::new(PWQUALITY_CONF).exists()
                || !std::fs::read_to_string(PWQUALITY_CONF)
                    .unwrap_or_default()
                    .contains("PinnacleCyPat"),
            "the dry run wrote to {PWQUALITY_CONF}"
        );
    }
}
